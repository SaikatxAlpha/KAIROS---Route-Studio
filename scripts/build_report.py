"""Generate docs/RESULTS.md from artifacts/experiments/*.json (no hand-typed numbers)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from kairos.config import EXPERIMENTS_DIR, REPO_ROOT  # noqa: E402

M = {"deterministic": "Deterministic baseline", "buffered": "Quantile buffer (ablation)",
     "saa_select": "Scenario selection (ablation)", "reliability": "KAIROS reliability"}
P = {"hold": "Hold + insert", "reoptimise": "Re-optimise", "reliability": "KAIROS replan"}


def load(name):
    p = EXPERIMENTS_DIR / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def sg(x, d=1, unit=""):
    return "n/a" if x is None else f"{x:+.{d}f}{unit}"


def ci(c, d=1):
    return "n/a" if not c else f"[{c[0]:.{d}f}, {c[1]:.{d}f}]"


def pv(p):
    return "n/a" if p is None else ("<0.001" if p < 0.001 else f"{p:.3f}")


def static_section(exp, key, title):
    s = exp["summaries"][key]
    out = [f"### {title}", "",
           f"Config: target {key.split('|')[2]}, uncertainty `{key.split('|')[0]}`, {exp['config']['iterations']} PyVRP iterations per planner, "
           f"{exp['config']['eval_scenarios']} out-of-sample scenarios, seed {exp['config']['seed']}. "
           f"Runs: {exp['n_runs']}, failed: {exp['n_failed']}.", "",
           "| Planner | On-time | All windows met | Lateness | Cost | Vehicles | Target met | Runtime (s) |",
           "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for e in s["overall"]:
        m = e["mean"]
        out.append(f"| {M[e['method']]} | {pct(m['on_time_rate'])} | {pct(m['p_all_on_time'], 0)} | {m['lateness_total_mean']:.1f} | "
                   f"{m['distance']:.1f} | {m['n_routes']:.2f} | {pct(e.get('target_attainment_rate'), 0)} | {e['runtime_s_mean']:.2f} |")
    out += ["", "Paired differences vs the deterministic baseline (mean, 95% bootstrap CI over instances, Wilcoxon p):", "",
            "| Scope | Planner | Δ on-time (pt) | 95% CI | p | Δ cost (%) | 95% CI | Δ vehicles |",
            "|---|---|---:|---|---:|---:|---|---:|"]
    for e in s["overall"] + s["by_group"]:
        if "paired_vs_baseline" not in e:
            continue
        p = e["paired_vs_baseline"]
        out.append(f"| {e['scope']} | {M[e['method']]} | {sg(p['on_time_rate_pt']['mean'], 2)} | {ci(p['on_time_rate_pt']['ci95'], 2)} | "
                   f"{pv(p['on_time_rate_pt']['wilcoxon_p'])} | {sg(p['distance_rel_pct']['mean'])} | {ci(p['distance_rel_pct']['ci95'])} | "
                   f"{sg(p['vehicles_delta']['mean'], 2)} |")
    return out + [""]


def main():
    lines = ["# KAIROS — measured results", "",
             "Generated by `scripts/build_report.py` from `artifacts/experiments/*.json`. Do not edit by hand.", "",
             "All variability and disruptions are synthetic (documented scenario model); plans are produced by PyVRP; "
             "metrics are measured by Monte Carlo simulation on scenario streams disjoint from the planners' in-sample scenarios. "
             "Experiment 6 uses real Amazon outcome data.", ""]
    s = load("static_solomon")
    if s:
        lines += ["## Experiment 1 — static planning and ablation", ""]
        lines += static_section(s, "medium|x1.0|0.95", "Solomon VRPTW, 56 instances")
    a = load("static_amazon")
    if a:
        for t in a["config"]["targets"]:
            lines += static_section(a, f"medium|x1.0|{t}", f"Amazon merged station-days ({len(a['config']['instances'])} instances), target {t}")
    t = load("target_sweep")
    if t:
        lines += ["## Experiment 2 — reliability target control (Solomon subset)", "",
                  "| Target | Achieved on-time | Target met on | Δ cost vs baseline |", "|---:|---:|---:|---:|"]
        for tg in t["config"]["targets"]:
            e = next(x for x in t["summaries"][f"medium|x1.0|{tg}"]["overall"] if x["method"] == "reliability")
            lines.append(f"| {pct(tg, 0)} | {pct(e['mean']['on_time_rate'])} | {pct(e['target_attainment_rate'], 0)} | "
                         f"{sg(e['paired_vs_baseline']['distance_rel_pct']['mean'])}% |")
        lines.append("")
    ms = load("misspecification")
    if ms:
        lines += ["## Experiment 3 — planner misspecification (Solomon subset, target 95%)", "",
                  "Planner assumes the true dispersion multiplied by the factor; evaluation world fixed at `medium`.", "",
                  "| Assumed × | Achieved on-time | Target met on | Δ cost |", "|---:|---:|---:|---:|"]
        for sc in ms["config"]["planner_scales"]:
            e = next(x for x in ms["summaries"][f"medium|x{float(sc)}|0.95"]["overall"] if x["method"] == "reliability")
            lines.append(f"| ×{sc} | {pct(e['mean']['on_time_rate'])} | {pct(e['target_attainment_rate'], 0)} | "
                         f"{sg(e['paired_vs_baseline']['distance_rel_pct']['mean'])}% |")
        lines.append("")
    ul = load("uncertainty_levels")
    if ul:
        lines += ["## Experiment 4 — sensitivity to variability level (Solomon subset)", "",
                  "| Level | Planner | On-time | Δ on-time (pt) | Δ cost (%) | Target met |", "|---|---|---:|---:|---:|---:|"]
        for lv in ul["config"]["levels"]:
            for e in ul["summaries"][f"{lv}|x1.0|0.95"]["overall"]:
                p = e.get("paired_vs_baseline")
                lines.append(f"| {lv} | {M[e['method']]} | {pct(e['mean']['on_time_rate'])} | "
                             f"{sg(p['on_time_rate_pt']['mean']) if p else '—'} | {sg(p['distance_rel_pct']['mean']) if p else '—'} | "
                             f"{pct(e['target_attainment_rate'], 0)} |")
        lines.append("")
    for name, label in (("dynamic_solomon", "Solomon subset"), ("dynamic_amazon", "Amazon")):
        d = load(name)
        if not d:
            continue
        lines += [f"## Experiment 5 — disruptions and replanning ({label})", "",
                  f"Events: {', '.join(d['config']['events'])}; {d['config']['repeats']} seeded repetitions per instance and base plan; "
                  f"{len(d['config']['instances'])} instances. Metrics cover the residual horizon after the event. "
                  f"Runs: {d['n_runs']}, failed: {d['n_failed']}.", "",
                  "| Base plan | Policy | On-time | Δ on-time vs baseline+hold (pt) | 95% CI | Δ residual cost (%) | Replan time (s) |",
                  "|---|---|---:|---:|---|---:|---:|"]
        for c in d["cells"]:
            if c["event"] != "all":
                continue
            p = c.get("paired_vs_det_hold", {})
            lines.append(f"| {M[c['base_method']]} | {P[c['policy']]} | {pct(c['mean']['on_time_rate'])} | "
                         f"{sg(p.get('on_time_rate_pt', {}).get('mean'), 2)} | {ci(p.get('on_time_rate_pt', {}).get('ci95'), 2)} | "
                         f"{sg(p.get('distance_rel_pct', {}).get('mean'))} | {c['mean']['runtime_s']:.2f} |")
        lines += ["", "On-time rate by event type:", "",
                  "| Base · policy | " + " | ".join(d["config"]["events"]) + " |",
                  "|---|" + "---:|" * len(d["config"]["events"])]
        combos = sorted({(c["base_method"], c["policy"]) for c in d["cells"]})
        for bm, pol in combos:
            row = [pct(next((c["mean"]["on_time_rate"] for c in d["cells"] if c["base_method"] == bm and c["policy"] == pol and c["event"] == ev), None))
                   for ev in d["config"]["events"]]
            lines.append(f"| {M[bm]} · {P[pol]} | " + " | ".join(row) + " |")
        lines.append("")
    tt = load("traveltime_model")
    if tt:
        lines += ["## Experiment 6 — travel-time estimation with calibrated uncertainty (real Amazon data)", "",
                  f"Train dates {tt['data']['split_dates']['train'][0]}–{tt['data']['split_dates']['train'][1]}, calibration "
                  f"{tt['data']['split_dates']['calibration'][0]}–{tt['data']['split_dates']['calibration'][1]}, test "
                  f"{tt['data']['split_dates']['test'][0]}–{tt['data']['split_dates']['test'][1]}; "
                  f"{tt['data']['n_train_arcs']:,} / {tt['data']['n_calibration_arcs']:,} / {tt['data']['n_test_arcs']:,} arcs.", "",
                  "| Metric (test dates) | LightGBM + CQR | Per-station speed fit |", "|---|---:|---:|",
                  f"| MAE | {tt['test']['mae_s']:.1f} s | {tt['baseline_speed_fit']['mae_s']:.1f} s |",
                  f"| Median absolute % error | {pct(tt['test']['median_ape'])} | {pct(tt['baseline_speed_fit']['median_ape'])} |"]
        for r, b in zip(tt["test"]["coverage"], tt["baseline_speed_fit"]["coverage"]):
            lines.append(f"| {pct(r['nominal'], 0)} interval: coverage (raw → conformal) / width | {pct(r['raw_coverage'])} → "
                         f"{pct(r['conformal_coverage'])} / ×{1 + r['conformal_rel_width']:.2f} | {pct(b['coverage'])} / ×{1 + b['rel_width']:.2f} |")
        lines += ["", "Caveats: " + " ".join(tt["caveats"]), ""]
    out = REPO_ROOT / "docs" / "RESULTS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
